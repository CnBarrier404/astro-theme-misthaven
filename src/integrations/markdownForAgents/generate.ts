import { copyFile, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";

import type { MarkdownDocument } from "./documents";

const PATH_MAP_NAME = "markdown-paths.map";
const TOKEN_MAP_NAME = "markdown-tokens.map";

interface MarkdownRoute {
  paths: string[];
  uri: string;
  tokenCount: number;
  advertiseCatalog?: boolean;
}

export async function generateMarkdownForAgents(root: string, distDir: string, documents: readonly MarkdownDocument[]) {
  const pathEntries: string[] = [];
  const workerRoutes: MarkdownRoute[] = [];

  for (const {
    href,
    markdown,
    filePath,
    uri = `${href}/index.md`,
    aliases = [`${href}/`],
    advertiseCatalog,
  } of documents) {
    const target = join(distDir, ...uri.slice(1).split("/").map(decodeURIComponent));
    const targetDir = dirname(target);
    await mkdir(targetDir, { recursive: true });
    await writeFile(target, markdown);

    if (filePath) await copyAssets(dirname(resolve(root, filePath)), targetDir);

    const paths = [href, ...aliases];
    pathEntries.push(...paths.map((path) => `${path} ${uri};`));
    workerRoutes.push({
      paths: [...paths, uri],
      uri,
      tokenCount: Math.ceil(markdown.trim().length / 4),
      advertiseCatalog,
    });
  }

  const tokenEntries = workerRoutes.flatMap(({ paths, tokenCount }) =>
    paths.map((path) => `${nginxRegex(path)} ${tokenCount};`),
  );
  await Promise.all([
    writeFile(join(distDir, PATH_MAP_NAME), nginxMap(pathEntries)),
    writeFile(join(distDir, TOKEN_MAP_NAME), nginxMap(tokenEntries)),
  ]);

  return workerRoutes;
}

export async function writeMarkdownWorker(distDir: string, routes: readonly MarkdownRoute[]) {
  const source = await readFile(new URL("./worker.mjs", import.meta.url), "utf8");
  const worker = `${source}\nexport default createMarkdownWorker(${JSON.stringify(routes)});\n`;
  await writeFile(join(distDir, "_worker.js"), worker);
}

async function copyAssets(sourceDir: string, targetDir: string) {
  const entries = await readdir(sourceDir, { withFileTypes: true, recursive: true });

  for (const entry of entries) {
    if (!entry.isFile() || entry.name.toLowerCase().endsWith(".md")) continue;

    const source = join(entry.parentPath, entry.name);
    const target = join(targetDir, relative(sourceDir, entry.parentPath), entry.name);
    await mkdir(dirname(target), { recursive: true });
    await copyFile(source, target);
  }
}

function nginxMap(entries: string[]) {
  return `# Generated by src/integrations/markdownForAgents/generate.ts.\ndefault "";\n${entries.join("\n")}\n`;
}

function nginxRegex(path: string) {
  return `~^${path.replace(/[\\^$.*+?()[\]{}|]/g, "\\$&")}$`;
}
